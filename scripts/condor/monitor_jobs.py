#!/usr/bin/env python3
"""
Condor Fun4All Job Completion Monitor

Monitors a directory containing Condor job output/stdout files (such as those
generated by genFun4All*.sh scripts). Periodically checks that all log files in
the directory have reached the final finish message (e.g. "Finished" or
"Finished successfully"). Once all jobs have completed, sends an email
notification to the user and exits.

Usage Examples:
    # Positional arguments: <dir> <interval> <email>
    python scripts/condor/monitor_jobs.py /sphenix/u/user/scratch/f4a/stdout 60 user@bnl.gov

    # Named arguments with time units (e.g. 30s, 5m, 1h):
    python scripts/condor/monitor_jobs.py --dir /sphenix/u/user/scratch/f4a --interval 5m --email user@bnl.gov

    # Specify expected number of jobs (if not auto-detected from jobs.list):
    python scripts/condor/monitor_jobs.py -d scratch/f4a/stdout -i 2m -e user@bnl.gov -n 120

    # Test email sending before starting monitoring:
    python scripts/condor/monitor_jobs.py --test-email --email user@bnl.gov

    # Check directory status once and exit (exit code 0 if all done, 1 if pending):
    python scripts/condor/monitor_jobs.py /sphenix/u/user/scratch/f4a/stdout --run-once
"""

