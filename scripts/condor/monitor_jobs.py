DEFAULT_FINISH_PATTERN = r"^\s*Finished(\s+successfully.*)?\s*$"
DEFAULT_ERROR_PATTERN = (
    r"(Error:\s*ROOT macro crashed"
    r"|Error:\s*cp failed permanently"
    r"|condor scratch NOT set"
    r"|Segmentation fault"
    r"|Fatal in <"
    r"|Bus error"
    r"|\bAborted\b)"
)
ERROR_BYTE_TOKENS = (
    b"Error:",
    b"ROOT macro crashed",
    b"cp failed permanently",
    b"condor scratch NOT set",
    b"Segmentation fault",
    b"Fatal in <",
    b"Bus error",
    b"Aborted",
)


def parse_interval(val: str) -> float:
    """Parses time intervals like '60', '30s', '5m', '1h', '0.5h' into seconds."""
    val = val.strip()
    match = re.match(r"^([0-9]+(?:\.[0-9]+)?)\s*([a-zA-Z]*)$", val)
    if not match:
        raise ValueError(
            f"Invalid interval format: '{val}'. Expected number of seconds (e.g. 60) or with unit (e.g. '30s', '5m', '1h')"
        )
    num = float(match.group(1))
    unit = match.group(2).lower()
    if unit in ("", "s", "sec", "second", "seconds"):
        return num
    if unit in ("m", "min", "minute", "minutes"):
        return num * 60.0
    if unit in ("h", "hr", "hour", "hours"):
        return num * 3600.0
    if unit in ("d", "day", "days"):
        return num * 86400.0
    raise ValueError(f"Unknown time unit '{unit}' in interval: '{val}'")


def format_duration(seconds: float) -> str:
    """Formats seconds into human-readable duration like '1h 23m 45s'."""
    sec_int = int(seconds)
    hours, remainder = divmod(sec_int, 3600)
    minutes, secs = divmod(remainder, 60)
    parts = []
    if hours > 0:
        parts.append(f"{hours}h")
    if minutes > 0 or hours > 0:
        parts.append(f"{minutes}m")
    parts.append(f"{secs}s")
    return " ".join(parts)


def send_email(
    to_email: str,
    subject: str,
    body: str,
    sender: str | None = None,
    smtp_server: str | None = None,
    smtp_port: int | None = None,
    smtp_user: str | None = None,
    smtp_password: str | None = None,
    smtp_tls: bool = False,
    smtp_ssl: bool = False,
    mail_cmd: str | None = None,
) -> tuple[bool, str]:
    """
    Sends an email using the best available mechanism:
    1. Specified mail command (e.g. mail, mailx, sendmail)
    2. Configured SMTP server
    3. Auto-detected local mail command (mailx, mail, /usr/sbin/sendmail)
    4. Localhost SMTP (localhost:25)

    Returns:
        (success, message)
    """
    hostname = socket.gethostname()
    if not sender:
        username = os.environ.get("USER", "root")
        sender = f"{username}@{hostname}"

    msg = MIMEText(body)
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = to_email
    msg["Date"] = email.utils.formatdate(localtime=True)

    errors = []

    # Method 1: If mail_cmd is explicitly passed
    if mail_cmd:
        try:
            cmd_name = os.path.basename(mail_cmd)
            if cmd_name in ("mail", "mailx"):
                proc = subprocess.run(
                    [mail_cmd, "-s", subject, to_email],
                    input=body,
                    text=True,
                    capture_output=True,
                    timeout=15,
                    check=False,
                )
            elif "sendmail" in cmd_name:
                proc = subprocess.run(
                    [mail_cmd, "-t", "-oi"],
                    input=msg.as_string(),
                    text=True,
                    capture_output=True,
                    timeout=15,
                    check=False,
                )
            else:
                proc = subprocess.run(
                    [mail_cmd, to_email],
                    input=body,
                    text=True,
                    capture_output=True,
                    timeout=15,
                    check=False,
                )

            if proc.returncode == 0:
                return True, f"Sent via command '{mail_cmd}'"
            err = proc.stderr.strip() or f"exit code {proc.returncode}"
            return False, f"Command '{mail_cmd}' failed: {err}"
        except Exception as e:
            return False, f"Failed executing '{mail_cmd}': {e}"

    # Method 2: If SMTP server is explicitly passed
    if smtp_server:
        port = smtp_port or (465 if smtp_ssl else (587 if smtp_tls else 25))
        password = smtp_password or os.environ.get("SMTP_PASSWORD", "")
        try:
            if smtp_ssl:
                server = smtplib.SMTP_SSL(smtp_server, port, timeout=15)
            else:
                server = smtplib.SMTP(smtp_server, port, timeout=15)

            if smtp_tls and not smtp_ssl:
                server.starttls()

            if smtp_user:
                server.login(smtp_user, password)

            server.send_message(msg)
            server.quit()
            return True, f"Sent via SMTP server {smtp_server}:{port}"
        except Exception as e:
            return False, f"SMTP delivery to {smtp_server}:{port} failed: {e}"

    # Method 3: Auto-detect local system tools (mailx / mail)
    for tool in ("mailx", "mail"):
        tool_path = shutil.which(tool)
        if tool_path:
            try:
                proc = subprocess.run(
                    [tool_path, "-s", subject, to_email],
                    input=body,
                    text=True,
                    capture_output=True,
                    timeout=15,
                    check=False,
                )
                if proc.returncode == 0:
                    return True, f"Sent via '{tool_path}'"
                errors.append(f"{tool} failed: {proc.stderr.strip()}")
            except Exception as e:
                errors.append(f"{tool} error: {e}")

    # Method 4: Auto-detect sendmail binary
    sendmail_paths = [
        shutil.which("sendmail"),
        "/usr/sbin/sendmail",
        "/usr/lib/sendmail",
    ]
    for s_path in sendmail_paths:
        if s_path and os.path.exists(s_path):
            try:
                proc = subprocess.run(
                    [s_path, "-t", "-oi"],
                    input=msg.as_string(),
                    text=True,
                    capture_output=True,
                    timeout=15,
                    check=False,
                )
                if proc.returncode == 0:
                    return True, f"Sent via '{s_path}'"
                errors.append(f"{s_path} failed: {proc.stderr.strip()}")
            except Exception as e:
                errors.append(f"{s_path} error: {e}")
            break

    # Method 5: Attempt localhost SMTP (127.0.0.1:25)
    try:
        server = smtplib.SMTP("127.0.0.1", 25, timeout=10)
        server.send_message(msg)
        server.quit()
        return True, "Sent via local SMTP relay (127.0.0.1:25)"
    except Exception as e:
        errors.append(f"Localhost SMTP (127.0.0.1:25) failed: {e}")

    summary = "; ".join(errors) if errors else "No mail utility or SMTP server found."
    return False, summary


def find_jobs_list(target_dir: Path) -> Path | None:
    """Searches target_dir and its parent for a jobs.list file."""
    candidates = [
        target_dir / "jobs.list",
        target_dir.parent / "jobs.list",
    ]
    for c in candidates:
        if c.is_file():
            return c
    return None


def count_jobs_in_list(jobs_list_path: Path) -> int:
    """Counts non-empty lines in a jobs.list file."""
    try:
        with jobs_list_path.open("r", encoding="utf-8", errors="ignore") as f:
            return sum(1 for line in f if line.strip())
    except Exception:
        return 0


def resolve_target_dir(raw_path: str, pattern: str) -> tuple[Path, str]:
    """
    Resolves target directory. If given directory has a 'stdout' subdirectory
    containing matching files, auto-resolves to 'stdout'.
    """
    p = Path(raw_path).expanduser().resolve()
    stdout_subdir = p / "stdout"
    if stdout_subdir.is_dir():
        # Fast check if parent directory itself contains matching files
        has_matches_in_parent = False
        try:
            with os.scandir(str(p)) as it:
                for entry in it:
                    if not entry.name.startswith(".") and fnmatch.fnmatch(entry.name, pattern) and entry.is_file():
                        has_matches_in_parent = True
                        break
        except OSError:
            pass

        if not has_matches_in_parent:
            return stdout_subdir, f"Resolved to subdirectory '{stdout_subdir}'"
    return p, ""


def inspect_log_file(
    file_path: str | Path,
    finish_regex: re.Pattern,
    error_regex: re.Pattern | None = None,
    max_bytes: int = 8192,
    size: int | None = None,
    finish_token: bytes | None = b"Finished",
) -> tuple[bool, str, str | None]:
    """
    Inspects the tail of a log file for finish message or errors.
    Optimized with fast byte-level pre-filtering and optional pre-computed file size.

    Returns:
        (is_finished: bool, status_desc: str, matched_line: str | None)
    """
    try:
        if size is None:
            size = os.path.getsize(file_path)

        if size == 0:
            return False, "File is empty (job starting)", None

        read_bytes = min(size, max_bytes)
        with open(file_path, "rb") as f:
            if size > read_bytes:
                f.seek(size - read_bytes)
            chunk = f.read(read_bytes)

        # Fast byte pre-filter:
        # Check if the finish token or any known error token is present in raw bytes.
        # This allows 99% of normal in-progress files to return instantly without line splitting or regex.
        has_finish = (finish_token is None) or (finish_token in chunk)
        has_error = (error_regex is not None) and any(token in chunk for token in ERROR_BYTE_TOKENS)

        if not has_finish and not has_error:
            return False, "In progress", None

        # Decode tail chunk only when a candidate token was detected
        text = chunk.decode("utf-8", errors="ignore")
        lines = [line.strip() for line in text.splitlines() if line.strip()]
        if not lines:
            return False, "No readable text", None

        # Check for finish message from the bottom up
        if has_finish:
            for line in reversed(lines):
                if finish_regex.search(line):
                    return True, "Finished", line

        # Check for known errors if not finished
        if has_error and error_regex:
            for line in reversed(lines):
                if error_regex.search(line):
                    return False, f"Failed: {line[:80]}", None

        return False, "In progress", None
    except Exception as e:
        return False, f"Read error: {e}", None


def generate_completion_report(
    target_dir: Path,
    start_time: datetime,
    check_count: int,
    total_files: int,
    completed_files: dict[str, str],
    failed_files: dict[str, str],
    finish_pattern_str: str,
    interval_sec: float,
    expected_jobs: int | None = None,
) -> str:
    """Builds a diagnostic completion report email."""
    now = datetime.now()
    duration_str = format_duration((now - start_time).total_seconds())
    hostname = socket.gethostname()
    try:
        fqdn = socket.getfqdn()
    except Exception:
        fqdn = hostname

    completed_count = len(completed_files)
    failed_count = len(failed_files)
    pct = (completed_count / total_files * 100.0) if total_files > 0 else 0.0

    if failed_count == 0 and completed_count == total_files:
        status_header = "ALL JOBS COMPLETED SUCCESSFULLY"
    elif failed_count > 0:
        status_header = f"COMPLETED WITH {failed_count} ERROR(S)"
    else:
        status_header = f"PARTIALLY COMPLETED ({completed_count}/{total_files})"

    # Sample completed files (up to 12)
    sample_completed = []
    for fname, match_line in list(completed_files.items())[:12]:
        sample_completed.append(f"  - {fname}: \"{match_line}\"")
    if len(completed_files) > 12:
        sample_completed.append(f"  ... and {len(completed_files) - 12} more completed files.")

    sample_completed_str = "\n".join(sample_completed) if sample_completed else "  (None)"

    # Failed files list (if any)
    failed_section = ""
    if failed_files:
        failed_lines = [f"  - {fname}: {err}" for fname, err in list(failed_files.items())[:15]]
        if len(failed_files) > 15:
            failed_lines.append(f"  ... and {len(failed_files) - 15} more failed files.")
        failed_section = f"""
Failed / Errored Jobs ({failed_count}):
----------------------------------------------------------------------
""" + "\n".join(failed_lines) + "\n"

    expected_info = f"Expected Jobs:       {expected_jobs}\n" if expected_jobs else ""

    report = f"""Hello,

This is an automated notification from {hostname}.

Status: {status_header}
Target Directory: {target_dir}

Execution Summary:
----------------------------------------------------------------------
Host:                {fqdn} ({hostname})
Directory:           {target_dir}
Total Files Found:   {total_files}
Finished Jobs:       {completed_count} ({pct:.1f}%)
Failed Jobs:         {failed_count}
{expected_info}Finish Pattern:      {finish_pattern_str}
Monitoring Started:  {start_time.strftime('%Y-%m-%d %H:%M:%S %Z')}
Completed At:        {now.strftime('%Y-%m-%d %H:%M:%S %Z')}
Total Wait Time:     {duration_str}
Checks Performed:    {check_count}
Check Interval:      {interval_sec:.1f}s

Sample Completed Files ({min(len(completed_files), 12)} shown):
----------------------------------------------------------------------
{sample_completed_str}
{failed_section}
----------------------------------------------------------------------
Notification generated by scripts/condor/monitor_jobs.py
"""
    return report


