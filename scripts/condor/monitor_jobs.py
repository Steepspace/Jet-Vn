def main() -> int:
    """Main CLI entry point for monitoring Condor Fun4All jobs."""
    parser = build_parser()
    args = parser.parse_args()

    # Resolve arguments (flags override positional)
    raw_dir = args.flag_dir or args.pos_dir
    raw_interval = args.flag_interval or args.pos_interval or "60s"
    email_addr = args.flag_email or args.pos_email

    mail_kwargs = {
        "sender": args.sender,
        "smtp_server": args.smtp_server,
        "smtp_port": args.smtp_port,
        "smtp_user": args.smtp_user,
        "smtp_password": args.smtp_password,
        "smtp_tls": args.smtp_tls,
        "smtp_ssl": args.smtp_ssl,
        "mail_cmd": args.mail_cmd,
    }

    # Handle test-email mode
    if args.test_email:
        if not email_addr:
            parser.error("Recipient email is required for --test-email. Specify via argument or --email.")
        print(f"Sending test email to {email_addr}...")
        test_subject = f"[Test] Condor Job Monitor Email Test from {socket.gethostname()}"
        test_body = (
            f"Hello,\n\n"
            f"This is a test notification from monitor_jobs.py on host {socket.gethostname()}.\n"
            f"If you received this message, your email configuration is working properly!\n\n"
            f"Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        )
        ok, msg = send_email(to_email=email_addr, subject=test_subject, body=test_body, **mail_kwargs)
        if ok:
            print(f"[SUCCESS] Test email sent successfully: {msg}")
            return 0
        print(f"[FAILED] Could not send test email: {msg}", file=sys.stderr)
        return 1

    # For monitoring or run-once, target directory is required
    if not raw_dir:
        parser.error("Target directory is required. Specify as first positional argument or via --dir.")

    # Parse interval
    try:
        interval = parse_interval(raw_interval)
        if interval <= 0:
            raise ValueError("Interval must be positive")
    except ValueError as e:
        parser.error(str(e))

    # For monitoring loop, recipient email is required
    if not args.run_once and not email_addr:
        parser.error("Recipient email is required. Specify as third positional argument or via --email.")

    # Compile regexes
    finish_pattern_str = args.finish_message or DEFAULT_FINISH_PATTERN
    try:
        finish_regex = re.compile(finish_pattern_str, re.IGNORECASE)
    except re.error as e:
        parser.error(f"Invalid finish-message regex '{finish_pattern_str}': {e}")

    error_regex = re.compile(DEFAULT_ERROR_PATTERN, re.IGNORECASE)

    # Pre-filter token for raw byte scanning
    finish_token: bytes | None = b"Finished"
    if args.finish_message:
        # If user passed custom finish regex, disable token pre-filter to guarantee regex correctness
        finish_token = None

    # Resolve target directory
    target_dir, resolve_note = resolve_target_dir(raw_dir, args.pattern)
    if resolve_note and not args.quiet:
        print(f"[INFO] {resolve_note}")

    # Detect expected jobs
    expected_jobs = args.expected_jobs
    jobs_list_file = find_jobs_list(target_dir)
    if expected_jobs is None and jobs_list_file:
        detected_count = count_jobs_in_list(jobs_list_file)
        if detected_count > 0:
            expected_jobs = detected_count
            if not args.quiet:
                print(f"[INFO] Auto-detected {expected_jobs} expected jobs from '{jobs_list_file}'")

    start_time = datetime.now()
    hostname = socket.gethostname()
    threads = max(1, args.threads)

    # Cache across checks
    completed_files: dict[str, str] = {}              # filename -> matched line
    failed_files: dict[str, str] = {}                 # filename -> error desc
    file_stat_cache: dict[str, tuple[int, int]] = {}  # filename -> (size, mtime_ns)

    # Optimize pattern matching: check if pattern is simple suffix like '*.out'
    is_suffix_pattern = args.pattern.startswith("*.") and "*" not in args.pattern[2:] and "?" not in args.pattern
    pattern_suffix = args.pattern[1:] if is_suffix_pattern else None

    def scan_directory(executor: ThreadPoolExecutor) -> tuple[int, int, int]:
        """
        Scans target_dir using os.scandir, mtime/size caching, and ThreadPoolExecutor.
        Returns:
            (total_count, done_count, in_prog_count)
        """
        target_dir_str = str(target_dir)
        if not os.path.isdir(target_dir_str):
            return 0, 0, 0

        entries_to_inspect = []
        matching_count = 0
        all_regular_count = 0

        try:
            with os.scandir(target_dir_str) as it:
                for entry in it:
                    name = entry.name
                    if name.startswith("."):
                        continue

                    matched = name.endswith(pattern_suffix) if pattern_suffix else fnmatch.fnmatch(name, args.pattern)

                    try:
                        if not entry.is_file():
                            continue
                    except OSError:
                        continue

                    all_regular_count += 1
                    if not matched:
                        continue

                    matching_count += 1
                    if name in completed_files:
                        continue

                    try:
                        st = entry.stat()
                        size = st.st_size
                        mtime_ns = st.st_mtime_ns
                    except OSError:
                        continue

                    current_stat = (size, mtime_ns)
                    prev_stat = file_stat_cache.get(name)

                    if prev_stat == current_stat:
                        # File has not changed since last check; status is unchanged
                        continue

                    if size == 0:
                        # 0-byte file: definitely empty/starting, record in cache and skip
                        file_stat_cache[name] = current_stat
                        continue

                    entries_to_inspect.append((entry.path, name, size, current_stat))
        except OSError as e:
            if not args.quiet:
                print(f"[WARNING] Could not scan directory {target_dir}: {e}", file=sys.stderr)
            return 0, len(completed_files), 0

        # Fallback: if no files matched pattern and pattern was default '*.out', check regular files
        if matching_count == 0 and args.pattern == "*.out" and all_regular_count > 0:
            try:
                with os.scandir(target_dir_str) as it:
                    for entry in it:
                        name = entry.name
                        if name.startswith("."):
                            continue
                        try:
                            if not entry.is_file():
                                continue
                            matching_count += 1
                            if name in completed_files:
                                continue
                            st = entry.stat()
                            size = st.st_size
                            mtime_ns = st.st_mtime_ns
                            current_stat = (size, mtime_ns)
                            if file_stat_cache.get(name) == current_stat:
                                continue
                            if size == 0:
                                file_stat_cache[name] = current_stat
                                continue
                            entries_to_inspect.append((entry.path, name, size, current_stat))
                        except OSError:
                            continue
            except OSError:
                pass

        # Inspect pending files in parallel
        if entries_to_inspect:
            def _worker(item):
                fpath, fname, fsize, fstat = item
                is_done, status, match_str = inspect_log_file(
                    fpath,
                    finish_regex=finish_regex,
                    error_regex=error_regex,
                    max_bytes=args.tail_bytes,
                    size=fsize,
                    finish_token=finish_token,
                )
                return fname, fstat, is_done, status, match_str

            if len(entries_to_inspect) == 1:
                results = [_worker(entries_to_inspect[0])]
            else:
                chunk_sz = min(128, max(1, len(entries_to_inspect) // (threads * 4)))
                results = executor.map(_worker, entries_to_inspect, chunksize=chunk_sz)

            for fname, fstat, is_done, status, match_str in results:
                file_stat_cache[fname] = fstat
                if is_done:
                    completed_files[fname] = match_str or "Finished"
                    failed_files.pop(fname, None)
                elif status.startswith("Failed:"):
                    failed_files[fname] = status
                else:
                    failed_files.pop(fname, None)

        total = max(matching_count, len(completed_files) + len(failed_files))
        done = len(completed_files)
        errs = len(failed_files)
        in_prog = max(0, total - done - errs)
        return total, done, in_prog

    executor = ThreadPoolExecutor(max_workers=threads)
    try:
        # Run-once mode
        if args.run_once:
            print(f"Scanning target directory: {target_dir}")
            print(f"Pattern: '{args.pattern}' | Finish Regex: '{finish_pattern_str}' | Threads: {threads}")
            total, done, in_prog = scan_directory(executor)

            print("=" * 70)
            print(f"Total files found:  {total}")
            if expected_jobs:
                print(f"Expected jobs:      {expected_jobs}")
            print(f"Completed jobs:     {done} ({(done / total * 100.0 if total > 0 else 0.0):.1f}%)")
            print(f"In-progress jobs:   {in_prog}")
            print(f"Failed jobs:        {len(failed_files)}")
            print("=" * 70)

            if failed_files:
                print("\nFailed jobs detected:")
                for fn, err in list(failed_files.items())[:10]:
                    print(f"  - {fn}: {err}")
                if len(failed_files) > 10:
                    print(f"  ... and {len(failed_files) - 10} more.")

            all_done = (done == total) and (total >= (expected_jobs or args.min_files)) and (total > 0)
            if all_done:
                print("[STATUS] ALL JOBS COMPLETED SUCCESSFULLY!")
                return 0
            print("[STATUS] Incomplete / pending jobs remaining.")
            return 1

        # Standard monitoring loop
        print("=" * 70)
        print("CONDOR FUN4ALL JOB COMPLETION MONITOR")
        print("=" * 70)
        print(f"  Target Dir:     {target_dir}")
        print(f"  File Pattern:   {args.pattern}")
        print(f"  Finish Pattern: {finish_pattern_str}")
        if expected_jobs:
            print(f"  Expected Jobs:  {expected_jobs}" + (" (from jobs.list)" if jobs_list_file else ""))
        print(f"  Interval:       {interval:.1f}s ({raw_interval})")
        print(f"  Threads:        {threads}")
        print(f"  Notification:   {email_addr}")
        print(f"  Host:           {hostname}")
        print(f"  Started:        {start_time.strftime('%Y-%m-%d %H:%M:%S')}")
        print("=" * 70)

        check_count = 0
        while True:
            check_count += 1
            now = datetime.now()
            elapsed_str = format_duration((now - start_time).total_seconds())

            if not target_dir.is_dir():
                if not args.quiet:
                    print(f"[{now.strftime('%H:%M:%S')}] Check #{check_count} (Elapsed: {elapsed_str}): Directory does not exist yet ({target_dir}). Waiting...")
                time.sleep(interval)
                continue

            total, done, in_prog = scan_directory(executor)

            # Check if expected files threshold is met
            threshold = expected_jobs if expected_jobs is not None else args.min_files

            if total == 0:
                if not args.quiet:
                    print(f"[{now.strftime('%H:%M:%S')}] Check #{check_count} (Elapsed: {elapsed_str}): No matching files found in {target_dir}. Waiting for jobs to produce output...")
                time.sleep(interval)
                continue

            pct = (done / total * 100.0) if total > 0 else 0.0
            fail_count = len(failed_files)

            # Check completion condition: all files in dir have the finish message
            if done == total and total >= threshold:
                print("\n" + "=" * 70)
                print(f"[{now.strftime('%Y-%m-%d %H:%M:%S')}] SUCCESS: All {done}/{total} jobs have completed successfully!")
                print(f"All files in '{target_dir}' contain the finish message.")
                print("=" * 70)

                subject = args.subject or f"[Done] All {done} Condor Jobs Completed on {hostname} ({target_dir.name})"
                body = generate_completion_report(
                    target_dir=target_dir,
                    start_time=start_time,
                    check_count=check_count,
                    total_files=total,
                    completed_files=completed_files,
                    failed_files=failed_files,
                    finish_pattern_str=finish_pattern_str,
                    interval_sec=interval,
                    expected_jobs=expected_jobs,
                )

                print(f"Sending notification email to {email_addr}...")
                ok, msg = send_email(to_email=email_addr, subject=subject, body=body, **mail_kwargs)
                if ok:
                    print(f"[SUCCESS] Email delivered successfully: {msg}")
                else:
                    print(f"[WARNING] Failed to deliver email: {msg}", file=sys.stderr)
                    print("=" * 70)
                    print("Report content was:")
                    print(body)
                    print("=" * 70)

                print("Task complete. Exiting.")
                return 0

            # Check terminal state with failures if requested
            if args.notify_on_failure and (done + fail_count == total) and total >= threshold and fail_count > 0:
                print("\n" + "=" * 70)
                print(f"[{now.strftime('%Y-%m-%d %H:%M:%S')}] ALL JOBS FINISHED with {fail_count} failure(s) ({done}/{total} succeeded).")
                print("=" * 70)

                subject = args.subject or f"[Alert] Condor Jobs Finished with Errors on {hostname} ({target_dir.name})"
                body = generate_completion_report(
                    target_dir=target_dir,
                    start_time=start_time,
                    check_count=check_count,
                    total_files=total,
                    completed_files=completed_files,
                    failed_files=failed_files,
                    finish_pattern_str=finish_pattern_str,
                    interval_sec=interval,
                    expected_jobs=expected_jobs,
                )

                print(f"Sending failure notification email to {email_addr}...")
                ok, msg = send_email(to_email=email_addr, subject=subject, body=body, **mail_kwargs)
                if ok:
                    print(f"[SUCCESS] Email delivered successfully: {msg}")
                else:
                    print(f"[WARNING] Failed to deliver email: {msg}", file=sys.stderr)

                return 1

            # Ongoing progress
            if not args.quiet:
                status_parts = [f"{done}/{total} finished ({pct:.1f}%)"]
                if in_prog > 0:
                    status_parts.append(f"{in_prog} in progress")
                if fail_count > 0:
                    status_parts.append(f"{fail_count} failed")
                if expected_jobs and total < expected_jobs:
                    status_parts.append(f"waiting for {expected_jobs - total} more output files")

                status_line = ", ".join(status_parts)
                print(f"[{now.strftime('%H:%M:%S')}] Check #{check_count} (Elapsed: {elapsed_str}): {status_line}")

            time.sleep(interval)

    except KeyboardInterrupt:
        total_time = format_duration((datetime.now() - start_time).total_seconds())
        print(f"\nMonitoring stopped by user after {check_count} checks ({total_time}). Exiting.")
        return 130
    finally:
        executor.shutdown(wait=False, cancel_futures=True)


if __name__ == "__main__":
    sys.exit(main())
